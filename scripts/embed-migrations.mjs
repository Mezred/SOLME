// Embeds db/migrations/*.sql into a TypeScript module so migrations ship inside serverless bundles.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = join(process.cwd(), "db", "migrations");
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
const entries = files.map((f) => ({ name: f.replace(/\.sql$/, ""), sql: readFileSync(join(dir, f), "utf8") }));

const out = `// AUTO-GENERATED by scripts/embed-migrations.mjs — do not edit. Source: db/migrations/*.sql
export const MIGRATIONS: { name: string; sql: string }[] = ${JSON.stringify(entries, null, 2)};
`;
writeFileSync(join(process.cwd(), "src", "lib", "db", "migrations.generated.ts"), out);
console.log(`Embedded ${entries.length} migration(s).`);
